package com.pioneers.rest.function_programming.ex;

public class Calculator {


    public int sum(final  int element1 , final int element2) {
        return element1 + element2;
    }

    public static int subtract(final  int element1 , final int element2) {
        return element1 - element2;
    }

    public static int multpliy(final  int element1 , final int element2) {
        return element1 * element2;
    }

    public static int divide(final  int element1 , final int element2) {
        return element1 / element2;
    }


}
